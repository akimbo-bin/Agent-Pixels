const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const createRoomStateStore=vm.runInNewContext(fs.readFileSync(path.resolve(__dirname,'../dev/engine/illustrated-room-states.js'),'utf8')+'\ncreateRoomStateStore;');
let now=100000;
const rooms=createRoomStateStore(()=>now);
const agent=(id,state,room='training')=>({id,name:id,room,state});
rooms.updateAgents([agent('one','working'),agent('two','idle')]);
assert.equal(rooms.state('training'),'working');
assert.equal(rooms.get('training').workingAgents,1);
rooms.updateAgents([agent('one','working'),agent('two','working')]);
rooms.updateAgents([agent('one','idle'),agent('two','working')]);
assert.equal(rooms.state('training'),'working','One worker stopping must not stop the room');
rooms.setRoomState('training','idle');
assert.equal(rooms.state('training'),'working','Room idle signal must not cancel another agent working');
rooms.updateAgents([agent('one','idle'),agent('two','paused')]);
assert.equal(rooms.state('training'),'idle');
rooms.setPreview('training','working');
assert.equal(rooms.state('training'),'working');
assert.equal(rooms.get('training').liveState,'idle');
assert.equal(rooms.get('training').workingAgents,0,'Preview must not invent working agents');
rooms.updateAgents([agent('one','waiting'),agent('two','idle')]);
assert.equal(rooms.state('training'),'working','Preview must survive a live update');
rooms.clearPreviews();
assert.equal(rooms.state('training'),'idle');
rooms.updateAgents([agent('one','running','data'),agent('two','idle')]);
assert.equal(rooms.state('data'),'working');
assert.equal(rooms.state('training'),'idle','Moving an agent must update both rooms');
now+=31000;
assert.equal(rooms.state('data'),'idle');
assert.equal(rooms.get('data').available,false,'Stale agent readings must not hold rooms Working');
rooms.setRoomState('training','working');
assert.equal(rooms.state('training'),'working','Fresh pipeline work can drive an unstaffed room');
assert.equal(rooms.updateAgents([agent('bad','idle','missing')]),false);
assert.equal(rooms.setPreview('missing','working'),false);
assert.equal(rooms.setRoomState('training','invalid'),false);
console.log('PASS any-agent aggregation, last-worker stop, assignment changes, preview/live separation, freshness, pipeline hook, input validation');
